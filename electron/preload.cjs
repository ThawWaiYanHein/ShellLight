const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('shelllight', {
  load: () => ipcRenderer.invoke('load'),
  save: (data, credential) => ipcRenderer.invoke('save', data, credential),
  connect: id => ipcRenderer.invoke('connect', id),
  openVSCode: id => ipcRenderer.invoke('open-vscode', id),
  sessionStart: id => ipcRenderer.invoke('session-start', id),
  sessionInput: (id, data) => ipcRenderer.send('session-input', id, data),
  sessionOutputAck: (id, size) => ipcRenderer.send('session-output-ack', id, size),
  sessionPaste: id => ipcRenderer.invoke('session-paste', id),
  sessionCopy: (id, text) => ipcRenderer.invoke('session-copy', id, text),
  sessionResize: (id, cols, rows) => ipcRenderer.invoke('session-resize', id, cols, rows),
  sessionClose: id => ipcRenderer.invoke('session-close', id),
  onSession: (id, callback) => { const listener = (_, sessionId, event) => { if (sessionId === id) callback(event); }; ipcRenderer.on('session-event', listener); return () => ipcRenderer.removeListener('session-event', listener); },
  pickKey: () => ipcRenderer.invoke('pick-key'),
  importSSH: () => ipcRenderer.invoke('import-ssh'),
  agentStatus: () => ipcRenderer.invoke('agent-status'),
  setupAgent: () => ipcRenderer.invoke('agent-setup'),
  unlockKey: file => ipcRenderer.invoke('agent-unlock', file),
});
